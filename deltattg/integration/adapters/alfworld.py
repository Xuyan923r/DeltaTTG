"""ALFWorld-only adapter for meter prefixes produced by verl-agent.

The meter was trained with the standalone ALFWorld envelope from
``agent_system.environments.protocols.alfworld``.  Verl-agent uses a different prompt for the actor, but
the observable state can still be represented losslessly in that envelope:
the environment manager supplies canonical observations, while assistant
responses are kept byte-for-byte as generated by the actor.
"""

from __future__ import annotations

from typing import Any

from agent_system.environments.protocols.alfworld import (
    METER_PREFIX_ADAPTER,
    SYSTEM_PROMPT,
    TOOL_SCHEMA,
)
from deltattg.meter.prompt import build_meter_messages


ADAPTER_NAME = METER_PREFIX_ADAPTER
METER_TOOLS = [TOOL_SCHEMA]


def build_alfworld_meter_messages(
    *,
    original_task: str,
    initial_observation: str,
    history_messages: list[dict[str, Any]],
    assistant_token_counts: list[int] | None,
    completed_turns: int,
    output_mode: str = "canonical_generation",
) -> list[dict[str, Any]]:
    """Wrap an ALFWorld state exactly like meter training examples.

    ``history_messages`` is intentionally not rewritten.  In particular, a
    verl-agent ``<think>...<action>...</action>`` response remains unchanged;
    only the surrounding meter envelope and observation representation are
    normalized.
    """

    return build_meter_messages(
        original_agent_system=SYSTEM_PROMPT,
        tools=METER_TOOLS,
        original_task=original_task,
        initial_observation=initial_observation,
        history_messages=history_messages,
        assistant_token_counts=assistant_token_counts,
        completed_turns=completed_turns,
        output_mode=output_mode,
    )
